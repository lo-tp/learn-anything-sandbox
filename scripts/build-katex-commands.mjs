#!/usr/bin/env node
/**
 * build:katex — derive the KaTeX command whitelist from the installed katex
 * package and write `core/katex-commands.ts` (the input to the `/api/compile`
 * LaTeX normalizer).
 *
 * The whitelist is the union of katex's *named control words* — the keys of
 * its `functions`, `macros`, and `symbols` (math + text) registries — filtered
 * to keys of the form *backslash + one or more ASCII letters*. It is regenerated on every
 * build (see package.json `build:sandbox`), so the normalizer tracks the
 * installed katex version instead of a hand-maintained list.
 *
 * The output records the katex version it was derived from; a test asserts
 * that version equals `require("katex").version`, so a katex bump that skips
 * regeneration fails the build.
 */
import { build } from "esbuild";
import { createRequire } from "node:module";
import { mkdtempSync, writeFileSync } from "node:fs";
import path from "node:path";
import os from "node:os";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const require_ = createRequire(import.meta.url);
const version = require_("katex/package.json").version;
const src = path.join(root, "node_modules", "katex", "src");

// Entry that unions the keys of katex's function / macro / symbol registries.
// The registries are TS with internal relative imports, so we bundle this
// entry with esbuild and read the exported `commands` array back.
const entry = [
  `import functions from ${JSON.stringify(path.join(src, "functions.ts"))};`,
  `import macros from ${JSON.stringify(path.join(src, "macros.ts"))};`,
  `import symbols from ${JSON.stringify(path.join(src, "symbols.ts"))};`,
  `const keys = new Set();`,
  `for (const k of Object.keys(functions)) keys.add(k);`,
  `for (const k of Object.keys(macros)) keys.add(k);`,
  `for (const k of Object.keys(symbols.math)) keys.add(k);`,
  `for (const k of Object.keys(symbols.text)) keys.add(k);`,
  `const FILTER = /^\\\\[A-Za-z]+$/;`,
  `export const commands = [...keys].filter((k) => FILTER.test(k)).sort();`,
].join("\n");

const tmp = mkdtempSync(path.join(os.tmpdir(), "katex-cmds-"));
const entryFile = path.join(tmp, "entry.mjs");
writeFileSync(entryFile, entry);

const result = await build({
  entryPoints: [entryFile],
  bundle: true,
  write: false,
  format: "esm",
  platform: "node",
  target: "es2020",
  logLevel: "silent",
});
const outFile = path.join(tmp, "out.mjs");
writeFileSync(outFile, result.outputFiles[0].text);

const mod = await import(pathToFileURL(outFile).href);
const commands = mod.commands;

const list = commands.map((c) => JSON.stringify(c)).join(", ");
const file = [
  `// core/katex-commands.ts — GENERATED by scripts/build-katex-commands.mjs; do not edit.`,
  `// katex@${version}`,
  `export const KATEX_VERSION = ${JSON.stringify(version)};`,
  `export const KATEX_COMMANDS: readonly string[] = [${list}];`,
  ``,
].join("\n");

writeFileSync(path.join(root, "core", "katex-commands.ts"), file);
console.log(`core/katex-commands.ts: ${commands.length} commands (katex@${version})`);
